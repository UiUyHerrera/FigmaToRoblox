// Writes docs/TAGS.md from the TAGS table in figma-plugin/code.js, so the docs
// always list the same tags and descriptions the plugin shows in its Interact tab.
// Usage: node tools/tags-doc.js
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const code = fs.readFileSync(path.join(root, "figma-plugin", "code.js"), "utf8");
const literal = code.match(/const TAGS\s*=\s*(\[[\s\S]*?\n\]);/);
if (!literal) throw new Error("TAGS table not found in figma-plugin/code.js");

// The table only holds strings and numbers, so evaluating our own source is safe.
const tags = new Function("return " + literal[1])();

const groups = new Map();
for (const [name, takesArg, group, description] of tags) {
  if (!groups.has(group)) groups.set(group, []);
  groups.get(group).push({ name, takesArg, description });
}

const escape = (s) => s.replace(/\|/g, "\\|");
let out = "# Tags\n\n";
out += "Add tags at the end of a layer name, separated by underscores (`Buy_button_smooth`), ";
out += "or pick them in the plugin's Interact tab. Tags marked with `:x` take an argument, like `_open:Shop`.\n\n";
out += `This file is generated by \`tools/tags-doc.js\` from \`figma-plugin/code.js\` (${tags.length} tags). Don't edit it by hand.\n`;
for (const [group, list] of groups) {
  out += `\n## ${group}\n\n| Tag | What it does |\n|---|---|\n`;
  for (const t of list) out += `| \`_${t.name}${t.takesArg ? ":x" : ""}\` | ${escape(t.description)} |\n`;
}

const file = path.join(root, "docs", "TAGS.md");
fs.mkdirSync(path.dirname(file), { recursive: true });
fs.writeFileSync(file, out);
console.log(`Wrote ${path.relative(root, file)} (${tags.length} tags)`);
